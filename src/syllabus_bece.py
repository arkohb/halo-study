def ordered_topic_ids(subject):
    """Topic ids in the order the syllabus runs, without duplicates."""
    seen, out = set(), []
    for _, items in SYLLABUS[subject]:
        for _, tid in items:
            if tid not in seen:
                seen.add(tid)
                out.append(tid)
    return out
